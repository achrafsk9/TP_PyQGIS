from qgis.PyQt.QtCore import QLocale, QTranslator, QCoreApplication
from qgis.core import QgsSettings
from qgis.PyQt.QtGui import QIcon
from qgis.PyQt.QtWidgets import QAction

# Import the code for the dialog
from .mon_extension_dialog import MonExtensionDialog
import os.path
import requests
from qgis.core import Qgis, QgsProject, QgsVectorLayer, QgsWkbTypes, QgsCoordinateReferenceSystem, QgsCoordinateTransform, QgsGeometry, QgsFeatureRequest, QgsFeature, QgsFillSymbol
from qgis.gui import QgsMapToolEmitPoint

class MonExtension:
    """QGIS Plugin Implementation."""

    def __init__(self, iface):
        """Constructor.

        :param iface: An interface instance that will be passed to this class
            which provides the hook by which you can manipulate the QGIS
            application at run time.
        :type iface: QgsInterface
        """
        # Save reference to the QGIS interface
        self.iface = iface
        # initialize plugin directory
        self.plugin_dir = os.path.dirname(__file__)
        # initialize locale
        locale = QgsSettings().value('locale/userLocale', QLocale().name())[0:2]
        locale_path = os.path.join(
            self.plugin_dir,
            'i18n',
            '{}.qm'.format(locale))

        if os.path.exists(locale_path):
            self.translator = QTranslator()
            self.translator.load(locale_path)
            QCoreApplication.installTranslator(self.translator)

        # Declare instance attributes
        self.actions = []
        self.menu = self.tr(u'&Mon Extension')

        # Check if plugin was started the first time in current QGIS session
        # Must be set in initGui() to survive plugin reloads
        self.first_start = None
        self.idCoucheTampon = None

    # noinspection PyMethodMayBeStatic
    def tr(self, message):
        """Get the translation for a string using Qt translation API.

        We implement this ourselves since we do not inherit QObject.

        :param message: String for translation.
        :type message: str, QString

        :returns: Translated version of message.
        :rtype: QString
        """
        # noinspection PyTypeChecker,PyArgumentList,PyCallByClass
        return QCoreApplication.translate('MonExtension', message)


    def add_action(
        self,
        icon_path,
        text,
        callback,
        enabled_flag=True,
        add_to_menu=True,
        add_to_toolbar=True,
        status_tip=None,
        whats_this=None,
        parent=None):
        """Add a toolbar icon to the toolbar.

        :param icon_path: Path to the icon for this action. Can be a resource
            path (e.g. ':/plugins/foo/bar.png') or a normal file system path.
        :type icon_path: str

        :param text: Text that should be shown in menu items for this action.
        :type text: str

        :param callback: Function to be called when the action is triggered.
        :type callback: function

        :param enabled_flag: A flag indicating if the action should be enabled
            by default. Defaults to True.
        :type enabled_flag: bool

        :param add_to_menu: Flag indicating whether the action should also
            be added to the menu. Defaults to True.
        :type add_to_menu: bool

        :param add_to_toolbar: Flag indicating whether the action should also
            be added to the toolbar. Defaults to True.
        :type add_to_toolbar: bool

        :param status_tip: Optional text to show in a popup when mouse pointer
            hovers over the action.
        :type status_tip: str

        :param parent: Parent widget for the new action. Defaults None.
        :type parent: QWidget

        :param whats_this: Optional text to show in the status bar when the
            mouse pointer hovers over the action.

        :returns: The action that was created. Note that the action is also
            added to self.actions list.
        :rtype: QAction
        """

        icon = QIcon(icon_path)
        action = QAction(icon, text, parent)
        action.triggered.connect(callback)
        action.setEnabled(enabled_flag)

        if status_tip is not None:
            action.setStatusTip(status_tip)

        if whats_this is not None:
            action.setWhatsThis(whats_this)

        if add_to_toolbar:
            # Adds plugin icon to Plugins toolbar
            self.iface.addToolBarIcon(action)

        if add_to_menu:
            self.iface.addPluginToMenu(
                self.menu,
                action)

        self.actions.append(action)

        return action

    def initGui(self):
        """Create the menu entries and toolbar icons inside the QGIS GUI."""

        icon_path = os.path.join(os.path.dirname(__file__), 'icon.png')
        self.add_action(
            icon_path,
            text=self.tr(u'Mon Extension'),
            callback=self.run,
            parent=self.iface.mainWindow())

        # will be set False in run()
        self.first_start = True


    def unload(self):
        """Removes the plugin menu item and icon from QGIS GUI."""
        for action in self.actions:
            self.iface.removePluginMenu(
                self.tr(u'&Mon Extension'),
                action)
            self.iface.removeToolBarIcon(action)

    def remplirListeCouches(self):
        self.dlg.comboCouches.clear()
        for couche in QgsProject.instance().mapLayers().values():
            if isinstance(couche, QgsVectorLayer) and couche.geometryType() == QgsWkbTypes.PointGeometry:
                self.dlg.comboCouches.addItem(couche.name(), couche.id())
    
    def displayPoint(self, point, button):
        crsCarte = self.canvas.mapSettings().destinationCrs()
        crsWgs84 = QgsCoordinateReferenceSystem("EPSG:4326")
        transformation = QgsCoordinateTransform(crsCarte, crsWgs84, QgsProject.instance())
        pointWgs84 = transformation.transform(point)
        self.dlg.labelLongitude.setText(f"Longitude : {pointWgs84.x():.5f}")
        self.dlg.labelLatitude.setText(f"Latitude : {pointWgs84.y():.5f}")
        self.afficherAdresse(pointWgs84)
        self.compterObjets(pointWgs84)
    
    def afficherAdresse(self, pointWgs84):
        url = "https://data.geopf.fr/geocodage/reverse"
        parametres = {
            "lon": pointWgs84.x(),
            "lat": pointWgs84.y(),
            "type": "housenumber",
            "limit": 1
        }
        try:
            reponse = requests.get(url, params=parametres, timeout=5)
            reponse.raise_for_status()
            resultats = reponse.json()["features"]
        except (requests.RequestException, ValueError, KeyError):
            self.dlg.labelAdresse.setText("Adresse : service indisponible")
            return

        if not resultats:
            self.dlg.labelAdresse.setText("Adresse : aucune adresse trouvée")
            return

        adresse = resultats[0]["properties"]
        self.dlg.labelAdresse.setText(
            f"Adresse : {adresse.get('housenumber', '')} {adresse.get('street', '')}, "
            f"{adresse.get('citycode', '')} {adresse.get('city', '')}"
        )
    
    def compterObjets(self, pointWgs84):
        self.dlg.labelNombreObjets.setText("Nombre d'objets :")

        try:
            distance = int(self.dlg.lineEditDistance.text())
        except ValueError:
            self.iface.messageBar().pushMessage(
                "Mon Extension", "La distance doit être un nombre entier.",
                level=Qgis.Critical, duration=5
            )
            return

        couche = QgsProject.instance().mapLayer(self.dlg.comboCouches.currentData())
        if couche is None:
            self.iface.messageBar().pushMessage(
                "Mon Extension", "Aucune couche de points sélectionnée.",
                level=Qgis.Warning, duration=5
            )
            return

        projet = QgsProject.instance()
        crsWgs84 = QgsCoordinateReferenceSystem("EPSG:4326")
        crsLambert93 = QgsCoordinateReferenceSystem("EPSG:2154")

        # Calcul du tampon en Lambert 93, dont l'unité est le mètre
        versLambert93 = QgsCoordinateTransform(crsWgs84, crsLambert93, projet)
        pointLambert93 = versLambert93.transform(pointWgs84)
        zoneTampon = QgsGeometry.fromPointXY(pointLambert93).buffer(distance, 25)

        # Passage de la zone tampon dans le système de la couche
        versCouche = QgsCoordinateTransform(crsLambert93, couche.crs(), projet)
        zoneTampon.transform(versCouche)

        # Présélection par emprise, puis test précis
        requete = QgsFeatureRequest().setFilterRect(zoneTampon.boundingBox())
        nombre = 0
        for objet in couche.getFeatures(requete):
            if objet.geometry().intersects(zoneTampon):
                nombre += 1

        self.dlg.labelNombreObjets.setText(
            f"Il y a {nombre} objet(s) à moins de {distance} mètres du point cliqué"
        )
        zoneTampon = QgsGeometry.fromPointXY(pointLambert93).buffer(distance, 25)
        self.afficherZoneTampon(zoneTampon)

    def afficherZoneTampon(self, zoneTampon):
        projet = QgsProject.instance()
        couche = projet.mapLayer(self.idCoucheTampon) if self.idCoucheTampon else None

        if couche is None:
            couche = QgsVectorLayer("Polygon?crs=EPSG:2154", "Zone tampon", "memory")
            symbole = QgsFillSymbol.createSimple({
                "style": "no",
                "outline_color": "#000000",
                "outline_width": "0.26"
            })
            couche.renderer().setSymbol(symbole)
            projet.addMapLayer(couche)
            self.idCoucheTampon = couche.id()

        fournisseur = couche.dataProvider()
        fournisseur.truncate()

        objet = QgsFeature()
        objet.setGeometry(zoneTampon)
        fournisseur.addFeatures([objet])

        couche.updateExtents()
        couche.triggerRepaint()

    def run(self):
        """Run method that performs all the real work"""
        if self.first_start == True:
            self.first_start = False
            self.dlg = MonExtensionDialog(self.iface.mainWindow())
            self.canvas = self.iface.mapCanvas()
            self.pointTool = QgsMapToolEmitPoint(self.canvas)
            self.pointTool.canvasClicked.connect(self.displayPoint)

        self.remplirListeCouches()
        self.canvas.setMapTool(self.pointTool)
        self.dlg.show()
